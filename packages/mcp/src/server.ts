/**
 * The one item a favorite or archive names: a media item by its `mediaId`, anything else by `assetType` + `id`. The
 * server decides which is valid and says so; this only passes on what was given, so the two cannot disagree.
 */
function namedTarget<A extends string, E extends Record<string, unknown>>(
  args: { mediaId?: string; assetType?: A; id?: string },
  extra: E,
): ({ mediaId: string } | { assetType: A; id: string }) & E {
  if (args.mediaId) return { mediaId: args.mediaId, ...extra }
  return { assetType: args.assetType as A, id: args.id ?? '', ...extra }
}

/** The bytes of a `data:` url, as an image block takes them. */
function inlineFromDataUrl(dataUrl: string): { data: string; mimeType: string } | null {
  const [, mimeType, data] = /^data:([^;,]+);base64,(.*)$/.exec(dataUrl) ?? []
  return mimeType && data ? { mimeType, data } : null
}

/**
 * What a still-running generation can already say about the shape of its own result, read from the tool's
 * own ARGUMENTS.
 *
 * ⚠️ **FROM `args`, NOT FROM THE BUILT REQUEST.** Every one of these sites builds its request inside a
 * `try`, so the request is out of scope in the `catch` where a pending outputId surfaces. `args` is the
 * handler's parameter and is always in scope, and it is also the more honest source: it is what the caller
 * asked for, which is exactly what the placeholders should depict.
 *
 * ⚠️ Read defensively because the count is spelled `numImages` on some tools and `numGenerations` on
 * others. A widened type here would be a third spelling; reading both is the whole reconciliation.
 *
 * ⛔ `auto` and `adaptive` are legal aspect inputs meaning "the model decides", so they are NOT ratios.
 * Passing one through would have the widget lay placeholders out against a string it cannot parse. Null
 * lets it fall back to its unshaped box, which is the honest state while nothing is known.
 */
function pendingShapeFrom(
  args: unknown,
  contentType: 'image' | 'video' | 'audio',
  /**
   * The submit response, which names the model from the registry. Absent on a path that never got one (a submit
   * that timed out with its outputId), where the card shows no chip rather than the id.
   */
  submitted?: Pick<GenerateResult, 'modelDisplayName' | 'modelBrandColor' | 'modelIconKey' | 'displayAspect'>,
): PendingShape {
  const a = (args ?? {}) as {
    modelId?: string
    aspectRatio?: string
    numImages?: number
    numGenerations?: number
    prompt?: string
    script?: string
  }
  // The shape the server recorded wins: it follows the input on a model whose output does. The ratio asked for is
  // only a stand-in on a path that never got a submit response.
  const ar = a.aspectRatio
  const asked = !ar || ar === 'auto' || ar === 'adaptive' || !ar.includes(':') ? null : ar
  const displayAspect = submitted?.displayAspect ?? asked
  return {
    contentType,
    modelId: a.modelId ?? '',
    displayAspect,
    expected: a.numImages ?? a.numGenerations ?? 1,
    /**
     * ⚠️ `script` IS THE PROMPT FOR LIP SYNC, where the words spoken are what a person recognizes the
     * card by. Falling back to it rather than showing nothing is the difference between a card that is
     * about something and a card that is about a model id.
     */
    prompt: a.prompt ?? a.script ?? null,
    modelName: submitted?.modelDisplayName ?? null,
    modelBrandColor: submitted?.modelBrandColor ?? null,
    modelIconKey: submitted?.modelIconKey ?? null,
  }
}

