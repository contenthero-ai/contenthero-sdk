  /**
   * ⭐⭐⭐ **THE GENERATION WIDGET: THE ONLY THING THAT PUTS A PLAYING VIDEO IN A CONVERSATION.**
   *
   * MCP's content blocks are `text | image | audio | resource | resource_link`. **There is no video block**,
   * so no arrangement of them can render video, and a `resource_link` renders as a hyperlink in ChatGPT and
   * as NOTHING in Claude. Measured in production 2026-09-19.
   *
   * MCP Apps is the mechanism that works. The server publishes an HTML resource under `ui://`, the host
   * mounts it, and the widget reads the tool's `structuredContent`. It is an open standard with an official
   * SDK (`@modelcontextprotocol/ext-apps`), verified against a working implementation before adoption.
   *
   * ⚠️ **THE HTML IS READ FROM THE PACKAGE, NOT FETCHED.** It ships inside the published tarball, so a local
   * install renders the same thing the hosted server does. Fetching it from our app would make the widget
   * depend on a deploy and break every offline or self-hosted install.
   *
   * ⛔ **REGISTERING THIS COSTS NOTHING FOR HOSTS THAT DO NOT SUPPORT IT.** A client that ignores `ui://`
   * resources simply never reads it, and the image and audio BLOCKS remain the fallback. That is why the
   * blocks stay rather than being replaced: two mechanisms, and the widget is the better one where it exists.
   */
  /**
   * ⚠️⚠️ **REGISTERED UNCONDITIONALLY, AND READ LAZILY.**
   *
   * This used to read the bundle at startup and register the resource only if it was found. Two problems.
   * A missing bundle produced a server that silently had no widget, which is the failure mode hardest to
   * notice: every tool still worked and nothing rendered. And the resource then did not exist when running
   * from `src/`, so the guard that checks tools point at a real resource could not run at all.
   *
   * ⭐ The resource is part of this server's contract. Advertising it always and throwing a NAMED error at
   * read time turns "no widget, no reason" into one line that says exactly what is missing.
   */
  /**
   * ⛔⛔⛔ **EVERY PUBLISH USED TO ORPHAN EVERY CONVERSATION THAT HAD ALREADY RENDERED A CARD.**
   *
   * The widget's uri carries the package version, which is deliberate: a host caches a `ui://` resource by
   * uri, so a stable one would keep serving last week's widget forever. The cost nobody accounted for is
   * that a transcript stores the uri it saw. Publishing 0.4.15 stopped serving
   * `generation-0.4.14.html`, and ChatGPT Desktop, which reopens past conversations from its own cache,
   * showed **"This app couldn't be loaded"** on every card it had previously rendered correctly. Measured
   * 2026-09-21. The web client escaped it only because it re-listed tools and got the new uri.
   *
   * ⭐⭐⭐ **SO ANY VERSION RESOLVES, AND IT RESOLVES TO THE CURRENT WIDGET.** The template below matches
   * every uri this package has ever minted and serves today's bundle for all of them. Cache-busting is
   * untouched, because a new conversation still gets a uri no host has cached. What changes is that an old
   * one is no longer pointed at nothing.
   *
   * ⚠️ SERVING THE CURRENT BUNDLE FOR AN OLD URI IS THE POINT, not a compromise. The widget renders from
   * `structuredContent` the host replays, and it is one app whose newest version is the one we want on
   * screen. Pinning historical bundles would mean shipping every past build forever to reproduce bugs we
   * have already fixed.
   *
   * ⚠️ `list: undefined` so the template adds nothing to `resources/list`. The concrete registration below
   * is what hosts discover; this one exists purely to answer reads for uris already in the wild.
   */
  server.resource(
    'generation-any-version',
    new ResourceTemplate('ui://contenthero/generation-{version}.html', { list: undefined }),
    { description: 'Any previously published generation widget, served as the current one.', mimeType: RESOURCE_MIME_TYPE, ...WIDGET_RESOURCE_META },
    async (uri) => ({
      contents: [{ uri: uri.href, mimeType: RESOURCE_MIME_TYPE, text: GENERATION_WIDGET_HTML, ...WIDGET_RESOURCE_META }],
    }),
  )

